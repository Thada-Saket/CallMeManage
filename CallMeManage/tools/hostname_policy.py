"""|===== นโยบายชื่ออุปกรณ์ (hostname) ที่ใช้ร่วมกันทั้งระบบ =====|

แยกออกมาเป็นไฟล์กลางเพราะ hostname ถูกกรอก/ใช้งานอยู่ 2 เส้นทางที่ไม่เกี่ยวกันเลย
และเดิมไม่มีการตรวจอะไรตรงกันสักเส้นทาง (bug 12):

  1. เส้นทาง NETCONF - ผู้ใช้กดเปลี่ยนชื่ออุปกรณ์จากหน้าเว็บ
     POST /devices/{dev_id}/command/set_hostname -> build_payload()
       -> vendor_translators/<vendor>.set_hostname() -> ยิง XML ไปที่อุปกรณ์

  2. เส้นทาง CLI generator - ผู้ใช้กรอกชื่อตอน onboarding อุปกรณ์ใหม่
     POST /cli/generate -> CliGenerateRequest -> backend/cli_generator.py
       -> ได้เป็นข้อความ CLI ให้ผู้ใช้ copy ไปวางบน console เอง

ถ้าปล่อยให้แต่ละเส้นทางเขียนกฎของตัวเอง กฎจะเพี้ยนออกจากกันแน่นอน (ซึ่งเกิดขึ้นจริง
มาแล้ว: ก่อนแก้ Huawei เช็ค 1-246, Juniper เช็ค 0-255 ซึ่งขอบล่างเป็น 0 แปลว่า
string ว่างผ่านได้ ส่วน Cisco กับ CLI generator ไม่เช็คอะไรเลยสักอย่าง)

--- ทำไมต้องจำกัดชุดตัวอักษร ไม่ใช่แค่ escape ---

escape() ป้องกันได้แค่เส้นทางที่ 1 (XML) เท่านั้น เส้นทางที่ 2 เป็น "ข้อความ CLI"
ธรรมดา ไม่มี escape ให้ใช้ - ตัวอักษรที่อันตรายที่สุดตรงนั้นคือ "ขึ้นบรรทัดใหม่"
ซึ่งทำให้ทุกอย่างหลัง \n กลายเป็นคำสั่งบรรทัดถัดไปบนอุปกรณ์ทันที เช่น

    hostname = "EDGE-1\nusername hacker privilege 15 secret x"

จะได้ config ที่มี user เพิ่มมาเงียบ ๆ โดยที่ผู้ใช้เห็นแค่ช่อง "ตั้งชื่ออุปกรณ์"

การจำกัด charset ตั้งแต่ต้นทางจึงเป็นด่านที่ปิดได้ทั้ง 2 เส้นทางพร้อมกัน ส่วน
escape() ยังคงต้องมีอยู่ในเส้นทาง XML เป็นด่านที่สอง (defense in depth) เผื่อวันหนึ่ง
มีใครเรียก set_hostname โดยข้ามฟังก์ชันนี้ไป

--- ที่มาของตัวเลข ---

* ความยาว 32: เป็น "นโยบายของโปรเจกต์" ที่เข้มกว่าขีดจำกัดจริงของอุปกรณ์โดยตั้งใจ
  YANG schema ของ Cisco เอง (device_capability/cisco/Cisco-IOS-XE-native.yang:1966)
  ระบุว่ารับได้ถึง 246 ตัวอักษร แต่ 246 คือ "ขีดที่อุปกรณ์ยอมรับ" ไม่ใช่ "ขีดที่ควรใช้"
  hostname ยาวขนาดนั้นจะทำให้ CLI prompt ยาวจนอ่าน output ไม่รู้เรื่อง

* charset [A-Za-z0-9_-]: เป็น subset ของ pattern ที่ YANG ของ Cisco กำหนดไว้อยู่แล้ว
  ('([0-9.]*[A-Za-z\\-_]+[A-Za-z0-9.\\-_]*)') โดยตัด "." ออกเพิ่มเพื่อไม่ให้ปนกับ FQDN
  และห้ามขึ้นต้นด้วยตัวเลขล้วนตาม RFC 1123 - ทั้ง 3 ยี่ห้อรับ charset ชุดนี้ได้หมด
"""

import re

# ความยาวสูงสุดของชื่ออุปกรณ์ (นโยบายโปรเจกต์ - เข้มกว่าที่อุปกรณ์รับได้จริง)
HOSTNAME_MAX_LENGTH = 32

# อนุญาตเฉพาะ A-Z a-z 0-9 - _ และต้องมีตัวอักษรอย่างน้อย 1 ตัว (ห้ามเป็นตัวเลขล้วน
# ตาม RFC 1123) - ห้ามขึ้นต้น/ลงท้ายด้วย "-" ตามข้อกำหนดของ hostname ทั่วไป
_HOSTNAME_RE = re.compile(r"^[A-Za-z0-9_](?:[A-Za-z0-9_-]*[A-Za-z0-9_])?$")

# ข้อความอธิบายกฎ - ใช้เป็นข้อความ error เดียวกันทุกที่ที่เรียก validate_hostname()
# (ฝั่ง frontend มี checklist ชุดเดียวกันใน CliGenerator.jsx ถ้าแก้ที่นี่ต้องไปแก้ที่นั่นด้วย)
HOSTNAME_RULE_TEXT = (
    f"ชื่ออุปกรณ์ต้องยาว 1-{HOSTNAME_MAX_LENGTH} ตัวอักษร "
    "ใช้ได้เฉพาะ A-Z a-z 0-9 ขีดกลาง (-) และขีดล่าง (_) "
    "ห้ามเว้นวรรค ห้ามขึ้นบรรทัดใหม่ ห้ามอักขระพิเศษหรือภาษาอื่น "
    "และห้ามขึ้นต้น/ลงท้ายด้วยขีดกลาง"
)


def validate_hostname(hostname: str) -> str:
    """ตรวจชื่ออุปกรณ์ตามนโยบายกลาง - คืนค่าเดิมถ้าผ่าน, โยน ValueError ถ้าไม่ผ่าน

    คืนค่ากลับมาด้วย (ไม่ใช่คืน None) เพื่อให้เรียกซ้อนในบรรทัดเดียวได้เลย เช่น
    f"<hostname>{escape(validate_hostname(hostname))}</hostname>"
    """
    if not isinstance(hostname, str):
        raise ValueError(HOSTNAME_RULE_TEXT)
    # ไม่ .strip() ให้เงียบ ๆ - ถ้าผู้ใช้พิมพ์ช่องว่างติดมา ควรบอกให้รู้ว่าผิด
    # ไม่ใช่แก้ให้เองแล้วได้ชื่อที่ไม่ตรงกับที่พิมพ์ (ฝั่ง frontend .trim() ให้ก่อนส่งแล้ว)
    if len(hostname) > HOSTNAME_MAX_LENGTH or not _HOSTNAME_RE.fullmatch(hostname):
        raise ValueError(f"{HOSTNAME_RULE_TEXT} (ได้รับ: {hostname!r})")
    return hostname
